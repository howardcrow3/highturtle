#!/usr/bin/env python3
"""Generate every token output from tokens.json (the single source).

Writes: tokens.css, dist/tailwind.preset.js, dist/TurtleboxTokens.swift,
and ../assets/styles.css (tokens.css + components/bundle.css) for the site.
Run: python3 turtlebox/design-system/build.py
"""
import json, pathlib, re
HERE = pathlib.Path(__file__).parent
T = json.loads((HERE / "tokens.json").read_text())
col = T["color"]["tokens"]
PALETTE = {t["name"] for t in col if t["usage"].startswith("Palette.")}
names = [t["name"] for t in col]
assert len(names) == len(set(names)), "duplicate color names"

def var(n): return f"--{n}"
def css_val(v):
    m = re.fullmatch(r"\{(.+)\}", v)
    return f"var({var(m.group(1))})" if m else v
def resolve(v, theme, seen=()):
    m = re.fullmatch(r"\{(.+)\}", v)
    if not m: return v
    t = next(x for x in col if x["name"] == m.group(1))
    tv = t["value"]; tv = tv[theme] if isinstance(tv, dict) else tv
    return resolve(tv, theme)
def themed(t, theme):
    v = t["value"]; return v[theme] if isinstance(v, dict) else v

fonts = T["type"]["fonts"]; fam = T["type"]["families"]
out = ["/* GENERATED by design-system/build.py from tokens.json. Do not edit. */", ""]
for f in fonts:
    out.append(f'@font-face {{ font-family: "{f["family"]}"; src: url("{f["file"]}") format("woff2"); font-weight: {f["weight"]}; font-style: {f["style"]}; font-display: swap; }}')
out += ["", ":root {", "  /* Palette */"]
for t in col:
    if t["name"] in PALETTE: out.append(f"  {var(t['name'])}: {themed(t,'light')};")
out.append("\n  /* Roles, light */")
for t in col:
    if t["name"] not in PALETTE: out.append(f"  {var(t['name'])}: {css_val(themed(t,'light'))};")
out.append("\n  /* Spacing, 8px base */")
for t in T["spacing"]["tokens"]: out.append(f"  --{t['name']}: {t['value']};")
out.append("\n  /* Type, shape, motion */")
out += [f"  --font-sans: {fam['sans']};"]
for t in T["radius"]["tokens"]: out.append(f"  --{t['name']}: {t['value']};")
for t in T["duration"]["tokens"]: out.append(f"  --{t['name']}: {t['value']};")
for t in T["easing"]["tokens"]: out.append(f"  --{t['name']}: {t['value']};")
out.append("}\n")
dark = [t for t in col if t["name"] not in PALETTE and isinstance(t["value"], dict) and t["value"]["light"] != t["value"]["dark"]]
body = "\n".join(f"    {var(t['name'])}: {css_val(themed(t,'dark'))};" for t in dark)
out.append(f'@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme="light"]) {{\n{body}\n  }}\n}}\n')
out.append(f':root[data-theme="dark"] {{\n{body.replace("    ","  ")}\n}}\n')
tokens_css = "\n".join(out)
(HERE / "tokens.css").write_text(tokens_css)

# Site stylesheet = tokens + components
bundle = (HERE / "components" / "bundle.css").read_text()
(HERE.parent / "assets" / "styles.css").write_text(tokens_css + "\n" + bundle)

# Tailwind preset
(HERE / "dist").mkdir(exist_ok=True)
tw_colors = {t["name"]: f"var({var(t['name'])})" for t in col}
preset = {
  "theme": {"extend": {
    "colors": tw_colors,
    "fontFamily": {"sans": [fam["sans"]]},
    "spacing": {t["name"].replace("space-", ""): f"var(--{t['name']})" for t in T["spacing"]["tokens"]},
    "borderRadius": {t["name"].replace("radius-", ""): t["value"] for t in T["radius"]["tokens"]},
    "transitionTimingFunction": {"out": "var(--ease-out)"},
  }}}
(HERE / "dist" / "tailwind.preset.js").write_text(
  "// GENERATED by design-system/build.py. Import tokens.css as well: colors resolve through CSS variables.\nmodule.exports = " + json.dumps(preset, indent=2) + ";\n")

# Swift
def sw(hexv): h = hexv.lstrip("#"); return f"0x{h.upper()}"
lines = ["// GENERATED by design-system/build.py from tokens.json. Do not edit.", "import SwiftUI", "",
         "public enum TurtleboxColor {"]
for t in col:
    if t["name"] in PALETTE: continue
    camel = re.sub(r"-(\w)", lambda m: m.group(1).upper(), t["name"])
    l, d = resolve(themed(t,"light"),"light"), resolve(themed(t,"dark"),"dark")
    lines.append(f"    public static let {camel} = Color(light: {sw(l)}, dark: {sw(d)})")
lines += ["}", "", "public enum TurtleboxSpace {"]
for t in T["spacing"]["tokens"]:
    camel = re.sub(r"-(\w)", lambda m: m.group(1).upper(), t["name"])
    lines.append(f"    public static let {camel}: CGFloat = {t['value'].replace('px','')}")
lines += ["}", "", "extension Color {",
 "    init(light: UInt32, dark: UInt32) {",
 "        self.init(UIColor { $0.userInterfaceStyle == .dark ? UIColor(rgb: dark) : UIColor(rgb: light) })",
 "    }", "}", "",
 "private extension UIColor {",
 "    convenience init(rgb: UInt32) {",
 "        self.init(red: CGFloat((rgb >> 16) & 0xFF) / 255, green: CGFloat((rgb >> 8) & 0xFF) / 255, blue: CGFloat(rgb & 0xFF) / 255, alpha: 1)",
 "    }", "}", ""]
(HERE / "dist" / "TurtleboxTokens.swift").write_text("\n".join(lines))
print("built tokens.css, dist/, ../assets/styles.css")
